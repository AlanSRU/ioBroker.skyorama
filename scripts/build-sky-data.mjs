// Builds www/js/skydata.js (stars, constellation figures, deep-sky objects) for the dome visualisation.
// Development tool only: run `node scripts/build-sky-data.mjs` when the data should change; the result is committed.
//
// Sources:
//   Yale Bright Star Catalogue 5th ed. (Hoffleit & Warren, 1991), via brettonw/YaleBrightStarCatalog bsc5-short.json
//   Constellation figures, names and label positions: d3-celestial by Olaf Frohn (BSD-3-Clause)

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const BSC = 'https://raw.githubusercontent.com/brettonw/YaleBrightStarCatalog/master/bsc5-short.json';
const LINES = 'https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data/constellations.lines.json';
const NAMES = 'https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data/constellations.json';
/** stars down to this magnitude: about what the eye sees from a dark garden */
const MAG_LIMIT = 5.0;

const get = async url => {
    const res = await fetch(url, { signal: AbortSignal.timeout(60_000) });
    if (!res.ok) {
        throw new Error(`${url}: HTTP ${res.status}`);
    }
    return res.json();
};
const r = (n, d) => Math.round(n * 10 ** d) / 10 ** d;
/** "00h 08m 23.3s" → hours */
const raHours = s => {
    const [, h, m, sec] = /(\d+)h (\d+)m ([\d.]+)s/.exec(s);
    return +h + m / 60 + sec / 3600;
};
/** "+29° 05′ 26″" → degrees */
const decDeg = s => {
    const [, sign, d, m, sec] = /([+-])(\d+)° (\d+)′ (\d+)″/.exec(s);
    return (sign === '-' ? -1 : 1) * (+d + m / 60 + sec / 3600);
};
/** d3-celestial longitude (−180…180 degrees) → right ascension in hours */
const lonToRa = lon => (((lon % 360) + 360) % 360) / 15;

const bsc = await get(BSC);
const stars = bsc
    .filter(s => s.RA && s.Dec && s.V && +s.V <= MAG_LIMIT)
    .map(s => {
        const star = [r(raHours(s.RA), 4), r(decDeg(s.Dec), 3), r(+s.V, 2), +s.K || 6000];
        return s.N ? [...star, s.N] : star;
    })
    .sort((a, b) => a[2] - b[2]);

const lines = await get(LINES);
const names = await get(NAMES);
// Serpens has two figures (Caput and Cauda) under the one id: name it Serpens, labelled at its head
const meta = new Map();
for (const f of names.features) {
    if (!meta.has(f.id)) {
        meta.set(f.id, f.id === 'Ser' ? { ...f, properties: { ...f.properties, name: 'Serpens' } } : f);
    }
}
const constellations = lines.features.map(f => {
    const m = meta.get(f.id);
    const [lon, dec] = m.geometry.coordinates;
    return [
        f.id,
        m.properties.name, // the standard name (Ursa Major, Cygnus …), as star charts use
        +m.properties.rank,
        r(lonToRa(lon), 3),
        r(dec, 2),
        f.geometry.coordinates.map(line => line.map(([l, d]) => [r(lonToRa(l), 4), r(d, 3)])),
    ];
});

